import 'package:flutter/material.dart';

/// Палитра для диаграмм — отдельная от палитры интерфейса.
///
/// Слоты фиксированы и назначаются по порядку, без циклического
/// повтора: порядок и есть механизм безопасности для дальтоников.
/// Значения не подбираются на глаз — они проверены на разделимость
/// при протанопии и дейтеранопии, на диапазон светлоты и насыщенности.
///
/// Проверка на белой карточке (#FFFFFF), 4 слота:
///   светлота, насыщенность, разделимость CVD, нормальное зрение — PASS
///   контраст: aqua 2,82:1 и yellow 2,17:1 ниже 3:1, поэтому у каждой
///   доли обязательна видимая подпись в легенде (она есть).
abstract final class ChartColors {
  static const slot1 = Color(0xFF2A78D6); // синий
  static const slot2 = Color(0xFFEB6834); // оранжевый
  static const slot3 = Color(0xFF1BAF7A); // бирюзовый
  static const slot4 = Color(0xFFEDA100); // жёлтый

  /// Порядок назначения. Пятая культура не получает новый оттенок —
  /// сгенерированный цвет неразличим под CVD; вместо этого излишек
  /// сворачивается в «прочее».
  static const series = [slot1, slot2, slot3, slot4];

  /// Незанятая земля и прочий фон — намеренно не из палитры серий:
  /// это не отдельная культура, а отсутствие данных.
  static const neutral = Color(0xFFDCE3DF);

  /// Максимум отдельных долей; остальное сворачивается в «прочее».
  static const maxSeries = 4;
}
